import pandas as pd

# 1. Loading individual SimScale result CSVs exported from parametric run
print("Loading individual SimScale CSV exports...")
ux_inlet = pd.read_csv('Wind Tunnel/Ux.csv')
ux_outlet = pd.read_csv('Wind Tunnel/Ux (1).csv')
p_inlet = pd.read_csv('Wind Tunnel/p.csv')
p_outlet = pd.read_csv('Wind Tunnel/p (1).csv')
k_inlet = pd.read_csv('Wind Tunnel/k.csv')
k_outlet = pd.read_csv('Wind Tunnel/k (1).csv')
omega_inlet = pd.read_csv('Wind Tunnel/omega.csv')
omega_outlet = pd.read_csv('Wind Tunnel/omega (1).csv')
nut_inlet = pd.read_csv('Wind Tunnel/nut.csv')
nut_outlet = pd.read_csv('Wind Tunnel/nut (1).csv')

# 2. Merging all dataframes sequentially on the 'Run #' column
master_df = (
    ux_inlet[['Run #', 'face33@Body4']]
    .rename(columns={'face33@Body4': 'Test_Velocity_V_test_ms'})
    .merge(
        p_inlet[['Run #', 'face33@Body4']].rename(
            columns={'face33@Body4': 'Pressure_Face33_Pa'}
        ),
        on='Run #',
    )
    .merge(
        p_outlet[['Run #', 'face71@Body4']].rename(
            columns={'face71@Body4': 'Pressure_Face71_Pa'}
        ),
        on='Run #',
    )
    .merge(
        k_inlet[['Run #', 'face33@Body4']].rename(
            columns={'face33@Body4': 'TKE_k_Face33'}
        ),
        on='Run #',
    )
    .merge(
        k_outlet[['Run #', 'face71@Body4']].rename(
            columns={'face71@Body4': 'TKE_k_Face71'}
        ),
        on='Run #',
    )
    .merge(
        omega_inlet[['Run #', 'face33@Body4']].rename(
            columns={'face33@Body4': 'Omega_Face33'}
        ),
        on='Run #',
    )
    .merge(
        omega_outlet[['Run #', 'face71@Body4']].rename(
            columns={'face71@Body4': 'Omega_Face71'}
        ),
        on='Run #',
    )
    .merge(
        nut_inlet[['Run #', 'face33@Body4']].rename(
            columns={'face33@Body4': 'Turb_Viscosity_nut_Face33'}
        ),
        on='Run #',
    )
    .merge(
        nut_outlet[['Run #', 'face71@Body4']].rename(
            columns={'face71@Body4': 'Turb_Viscosity_nut_Face71'}
        ),
        on='Run #',
    )
)

# 3. Adding a calculated Pressure Drop column (Face 33 minus Face 71)
master_df['Pressure_Drop_Pa'] = (
    master_df['Pressure_Face33_Pa'] - master_df['Pressure_Face71_Pa']
)

# Reordering columns for better readability
cols = ['Run #', 'Test_Velocity_V_test_ms', 'Pressure_Face33_Pa', 'Pressure_Face71_Pa', 'Pressure_Drop_Pa']
other_cols = [c for c in master_df.columns if c not in cols]
master_df = master_df[cols + other_cols]

# 4. Saving to a single CSV file
output_filename = 'simscale_combined_results.csv'
master_df.to_csv(output_filename, index=False)

print(f"\nSuccessfully generated '{output_filename}'!")
print(f"Total rows (runs): {len(master_df)}")
print("\nPreview of merged data:")
print(master_df.head())

